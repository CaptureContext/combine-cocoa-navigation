import MacroToolkit
import SwiftDiagnostics
import SwiftSyntax
import SwiftSyntaxMacros

extension RoutingControllerMacro {
	struct NavigationDestinations {
		var tree: [Variable] = []
		var stack: [Variable] = []
		var derived: [Variable] = []
		var presentation: [Variable] = []

		mutating func append(
			_ member: Variable,
			to type: RoutingControllerMacro.DestinationType
	 ) {
			switch type {
			case .tree: tree.append(member)
			case .stack: stack.append(member)
			case .derived: derived.append(member)
			case .presentation: presentation.append(member)
			}
		}

		func toDictionary() -> Dictionary<DestinationType, [Variable]> {
			[
				.tree: tree,
				.stack: stack,
				.derived: derived,
				.presentation: presentation
			]
		}
	}

	enum DestinationType: String, CaseIterable {
		case tree = "TreeDestination"
		case stack = "StackDestination"
		case derived = "DerivedDestination"
		case presentation = "PresentationDestination"

		var pluralName: String {
			rawValue + "s"
		}
	}

	static func getDestinations(
		from declaration: ClassDeclSyntax
	) -> NavigationDestinations  {
		var navigationDestinations = NavigationDestinations()

		declaration.memberBlock.members.forEach { member in
			guard let variable = Variable(member.decl) else { return }

			for attribute in variable.attributes {
				if
					case let .attribute(attribute) = attribute,
					let type = DestinationType.allCases.first(
						where: { attribute.name.name.contains($0.rawValue ) }
					)
				{
					navigationDestinations.append(variable, to: type)
					return
				}
			}
		}

		return navigationDestinations
	}
}

extension RoutingControllerMacro {
	fileprivate struct ProducedExtensionMembers {
		var types: [MemberBlockItemSyntax] = []
		var methods: [MemberBlockItemSyntax] = []
	}

	/// Creates an array of MemberBlockItemSyntax from
	static func makeDeclarationsExtensionMembers(
		for declaration: ClassDeclSyntax
	) throws -> [MemberBlockItemSyntax] {
		var producedExtensionMembers = ProducedExtensionMembers()
		let navigationDestinations = getDestinations(from: declaration)

		navigationDestinations.toDictionary().sorted(by: {
			let order: [DestinationType] = [.stack, .tree, .derived, .presentation]
			return (order.firstIndex(of: $0.key) ?? -1) < (order.firstIndex(of: $1.key) ?? -1)
		}).forEach { type, members in
			processDestinations(
				ofType: type,
				members: members,
				into: &producedExtensionMembers
			)
		}

		producedExtensionMembers.methods.popLast().map { method in
			producedExtensionMembers.methods.append(method.with(\.trailingTrivia, .newline))
		}

		return producedExtensionMembers.types
		+ producedExtensionMembers.methods
	}

	fileprivate static func processDestinations(
		ofType type: DestinationType,
		members: [Variable],
		into producedExtensionMembers: inout ProducedExtensionMembers
	) {
		let additionalMembers: [MemberBlockItemSyntax] = switch type {
		case .stack: [makeStackDestinationsSubscriptDecl(for: members)]
		default: []
		}

		producedExtensionMembers.types.append(makeDestinationsStructDecl(
			ofType: type,
			members: members,
			additionalMembers: additionalMembers
		))

		producedExtensionMembers.methods.append(makeDestinationProducingMethodDecl(
			for: type,
			members: members
		))
	}

	fileprivate static func makeDestinationsStructDecl(
		ofType type: DestinationType,
		members: [Variable],
		additionalMembers: [MemberBlockItemSyntax] = []
	) -> MemberBlockItemSyntax {
		return MemberBlockItemSyntax(
			decl: StructDeclSyntax(
				leadingTrivia: Trivia.init(
					pieces: makeDestinationStructDocComment(for: type)
						.components(separatedBy: .newlines)
						.flatMap { [.docLineComment($0), .newlines(1)] }
				),
				modifiers: DeclModifierListSyntax {
					DeclModifierSyntax(name: "public")
				},
				name: .identifier(type.pluralName),
				inheritanceClause: InheritanceClauseSyntax(
					inheritedTypes: InheritedTypeListSyntax {
						InheritedTypeSyntax(type: TypeSyntax(stringLiteral: "DestinationsProtocol"))
					}
				),
				memberBlock: MemberBlockSyntax(
					members: MemberBlockItemListSyntax(
						makeAllDestinations(ofType: type, members: members)
						+ members.map {
							MemberBlockItemSyntax(decl: $0._syntax)
						}
						+ additionalMembers
					)
				),
				trailingTrivia: .newlines(2)
			)
		)
	}

	fileprivate static func makeDestinationStructDocComment(for type: DestinationType) -> String {
		return """
		/// Container for captured destinations without referring to self
		///
		/// > Generated by `CombineNavigationMacros.RoutingController` macro
		"""
	}

	fileprivate static func makeAllDestinations(
		ofType type: DestinationType,
		members: [Variable]
	) -> [MemberBlockItemSyntax] {
		let ids = members
			.compactMap { member in
				member.bindings.first?.identifier
			}
			.map { "_\($0)"}
			.joined(separator: ",\n")

		return [
			.literal {
				"public typealias DestinationType = _\(raw: type.rawValue)Protocol"
			},
			.literal {
				"""
				public var allDestinations: [any DestinationType] {
					return [\(raw: ids)]
				}
				"""
			}
		]
	}

	fileprivate static func makeStackDestinationsSubscriptDecl(
		for members: [Variable]
	) -> MemberBlockItemSyntax {
		if members.isEmpty {
			return .literal {
				"""
				\npublic subscript(_ id: some Hashable) -> UIViewController? {
					return nil
				}
				"""
			}
		} else {
			let castedIDDecl: DeclSyntax = """
			func controller<ID, Controller>(
				for destination: StackDestination<ID, Controller>
			) -> UIViewController? {
				return (id as? ID).flatMap {
					destination.wrappedValue[$0]
				}
			}
			"""

			var stackDestinationsCoalecing: String {
				return members
					.compactMap { $0.bindings.first.flatMap(\.identifier) }
					.map { "controller(for: _\($0))" }
					.joined(separator: "\n\t?? ")
			}

			return .literal {
				"""
				\npublic subscript(_ id: some Hashable) -> UIViewController? {
					\(castedIDDecl)

					return \(raw: stackDestinationsCoalecing)
				}
				"""
			}
		}
	}

	fileprivate static func makeDestinationsInitParams(
		with members: [Variable]
	) -> String {
		members
			.compactMap { $0.bindings.first.flatMap(\.identifier).map { "\($0): $\($0)" } }
			.joined(separator: ",\n")
	}

	fileprivate static func makeDestinationProducingMethodDecl(
		for type: DestinationType,
		members: [Variable] = []
	) -> MemberBlockItemSyntax {
		let initParams = makeDestinationsInitParams(with: members)

		switch initParams.isEmpty {
		case true:
			return .literal {
				"""
				@_spi(Internals)
				public func _make\(raw: type.pluralName)() -> \(raw: type.pluralName) {
					return \(raw: type.pluralName)()
				}
				"""
			}.with(\.trailingTrivia, .newlines(2))
		case false:
			return .literal {
				"""
				@_spi(Internals)
				public func _make\(raw: type.pluralName)() -> \(raw: type.pluralName) {
					return \(raw: type.pluralName)(
						\(raw: initParams)
					)
				}
				"""
			}.with(\.trailingTrivia, .newlines(2))
		}
	}
}

extension MemberBlockItemSyntax {
	static func literal(_ decl: () -> DeclSyntax) -> MemberBlockItemSyntax {
		MemberBlockItemSyntax(decl: decl())
	}
}
