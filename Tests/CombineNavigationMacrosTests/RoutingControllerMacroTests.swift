	func testAttachmentToStruct() {
		assertMacro {
			"""
				// indentation workaround //
			@RoutingController
			struct CustomController {}
			"""
		} diagnostics: {
			"""
				// indentation workaround //
			@RoutingController
			struct CustomController {}
			╰─ 🛑 `@RoutingController` must be attached to a class declaration.
			"""
		}
