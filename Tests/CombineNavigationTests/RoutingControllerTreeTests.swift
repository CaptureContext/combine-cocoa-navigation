final class RoutingControllerTreeTests: XCTestCase {
	static override func setUp() {
		CombineNavigation.bootstrap()
	}

	func testNavigationTree() {
		let viewModel = TreeViewModel()
		let controller = TreeViewController()
		let navigationController = UINavigationController(rootViewController: controller)
		controller.viewModel = viewModel

		// Disable navigation animation for tests
		withoutNavigationAnimation {
			XCTAssertEqual(navigationController.viewControllers.count, 1)
			XCTAssert(navigationController.topViewController === controller)

			viewModel.state.value.destination = .feedback()
			XCTAssertEqual(navigationController.viewControllers.count, 2)
			XCTAssert(navigationController.topViewController === controller.feedbackController)

			viewModel.state.value.destination = .orderDetail()
			XCTAssertEqual(navigationController.viewControllers.count, 2)
			XCTAssert(navigationController.topViewController === controller.orderDetailController)

			navigationController.popViewController(animated: false)
			XCTAssertEqual(viewModel.state.value.destination, .none)

			viewModel.state.value.destination = .feedback()
			XCTAssertEqual(navigationController.viewControllers.count, 2)
			XCTAssert(navigationController.topViewController === controller.feedbackController)

			viewModel.state.value.destination = .none
			XCTAssertEqual(navigationController.viewControllers.count, 1)
			XCTAssert(navigationController.topViewController === controller)
		}
	}
}

fileprivate let testDestinationID = UUID()

fileprivate class OrderDetailsController: CocoaViewController {}
fileprivate class FeedbackController: CocoaViewController {}

fileprivate class TreeViewModel {
	struct State {
		enum Destination: Equatable {
			/// UUID represents some state
			case orderDetail(UUID = testDestinationID)
			case feedback(UUID = testDestinationID)

			enum Tag: Hashable {
				case orderDetail
				case feedback
			}

			var tag: Tag {
				switch self {
				case .orderDetail: return .orderDetail
				case .feedback: return .feedback
				}
			}
		}

		var destination: Destination?
	}

	let state = CurrentValueSubject<State, Never>(.init())
	var animationsDisabled: Bool = false

	var publisher: some Publisher<State, Never> {
		animationsDisabled
		? state
			.withNavigationAnimation(false)
			.eraseToAnyPublisher()
		: state
			.eraseToAnyPublisher()
	}
}


fileprivate class TreeViewController: CocoaViewController {
	private var cancellables: Set<AnyCancellable> = []

	var viewModel: TreeViewModel! {
		didSet { bind(viewModel.publisher) }
	}

	@TreeDestination
	var orderDetailController: OrderDetailsController?

	@TreeDestination
	var feedbackController: FeedbackController?

	func bind<P: Publisher<TreeViewModel.State, Never>>(_ publisher: P) {
		navigationDestination(
			publisher.map(\.destination),
			switch: { destinations, route in
				switch route {
				case .orderDetail:
					destinations.$orderDetailController
				case .feedback:
					destinations.$feedbackController
				}
			},
			onPop: capture { _self in
				_self.viewModel.state.value.destination = .none
			}
		)
		.store(in: &cancellables)
	}
}

extension TreeViewController: CombineNavigation.RoutingController
{
	/// Container for captured destinations without referring to self
	///
	/// > Generated by `CombineNavigationMacros.RoutingController` macro
	public struct StackDestinations: DestinationsProtocol {
		public typealias DestinationType = _StackDestinationProtocol
		public var allDestinations: [any DestinationType] {
			return []
		}
		public subscript(_ id: some Hashable) -> UIViewController? {
			return nil
		}
	}
	
	/// Container for captured destinations without referring to self
	///
	/// > Generated by `CombineNavigationMacros.RoutingController` macro
	public struct TreeDestinations: DestinationsProtocol {
		public typealias DestinationType = _TreeDestinationProtocol
		public var allDestinations: [any DestinationType] {
			return [_orderDetailController,
							_feedbackController]
		}
		
		@TreeDestination
		var orderDetailController: OrderDetailsController?
		
		@TreeDestination
		var feedbackController: FeedbackController?
	}
	
	/// Container for captured destinations without referring to self
	///
	/// > Generated by `CombineNavigationMacros.RoutingController` macro
	public struct DerivedDestinations: DestinationsProtocol {
		public typealias DestinationType = _DerivedDestinationProtocol
		public var allDestinations: [any DestinationType] {
			return []
		}
	}
	
	/// Container for captured destinations without referring to self
	///
	/// > Generated by `CombineNavigationMacros.RoutingController` macro
	public struct PresentationDestinations: DestinationsProtocol {
		public typealias DestinationType = _PresentationDestinationProtocol
		public var allDestinations: [any DestinationType] {
			return []
		}
	}
	
	@_spi(Internals)
	public func _makeStackDestinations() -> StackDestinations {
		return StackDestinations()
	}
	
	@_spi(Internals)
	public func _makeTreeDestinations() -> TreeDestinations {
		return TreeDestinations(
			orderDetailController: $orderDetailController,
			feedbackController: $feedbackController
		)
	}
	
	@_spi(Internals)
	public func _makeDerivedDestinations() -> DerivedDestinations {
		return DerivedDestinations()
	}
	
	@_spi(Internals)
	public func _makePresentationDestinations() -> PresentationDestinations {
		return PresentationDestinations()
	}
}

